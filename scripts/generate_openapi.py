#!/usr/bin/env python3
"""Deterministically generate the canonical OpenAPI 3.1 contract.

Invoked by `python scripts/dev.py openapi` (or `--check`).
Output: `contracts/openapi/openapi.json` — DO NOT EDIT MANUALLY.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "contracts" / "openapi" / "openapi.json"

HEADER = "DO NOT EDIT MANUALLY - generated by python scripts/dev.py openapi"


def build_spec_dict() -> dict:
    from crm_bds_ai.bootstrap.app import create_app

    spec = create_app().openapi()
    return {"x-generated-by": HEADER, **spec}


def serialize(spec: dict) -> str:
    return json.dumps(spec, ensure_ascii=False, sort_keys=True, indent=2) + "\n"


def main() -> int:
    if "--check" in sys.argv:
        spec = build_spec_dict()
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != serialize(spec):
            print(f"DRIFT DETECTED: {OUT} differs from generated output. Run: python scripts/dev.py openapi")
            return 1
        print(f"OK: {OUT} matches generated output (deterministic, no drift).")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(serialize(build_spec_dict()), encoding="utf-8")
    print(f"Generated {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
